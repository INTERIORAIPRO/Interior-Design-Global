const DISTRIBUTOR_HOSTS = ["thehome.ro", "thehome.com"];

export function officialManufacturerUrl(vendorId?: string, fallbackUrl?: string) {
  const vendor = getVendor(vendorId);
  if (vendor?.storeUrl) return vendor.storeUrl;
  const fallback = fallbackUrl?.trim() ?? "";
  if (!fallback) return "https://kavehome.com";
  try {
    const host = new URL(fallback).hostname.replace(/^www\./, "");
    if (DISTRIBUTOR_HOSTS.some((blocked) => host.endsWith(blocked))) {
      return "https://kavehome.com";
    }
  } catch {
    return "https://kavehome.com";
  }
  return fallback;
}

export function isRealProductPhoto(url?: string | null) {
  const value = url?.trim() ?? "";
  if (!value || /\.svg(\?|$)/i.test(value)) return false;
  if (!/\.(jpe?g|webp)(\?|$)/i.test(value)) return false;
  if (value.includes("/partner-store/")) return false;
  return value.startsWith("/products/") || /^https?:\/\//i.test(value);
}

export function isDisplayableProductImage(url?: string | null) {
  return isRealProductPhoto(url);
}

export function studioCatalogImage(
  product: Pick<PartnerProduct, "name" | "category">,
) {
  const name = product.name.toLowerCase();
  if (
    name.includes("tv") ||
    name.includes("media") ||
    product.category === "sideboard"
  ) {
    return "/products/studio/tv.jpg";
  }
  if (product.category === "beds" || name.startsWith("pat ") || name.includes("pat ")) {
    return "/products/studio/bed.jpg";
  }
  if (name.includes("noptier")) return "/products/studio/nightstand.jpg";
  if (
    name.includes("pendul") ||
    name.includes("pendant") ||
    name.includes("suspend")
  ) {
    return "/products/studio/pendant.jpg";
  }
  if (
    name.includes("pouf") ||
    name.includes("puf") ||
    name.includes("taburet") ||
    name.includes("banchet") ||
    name.includes("ottoman")
  ) {
    return "/products/studio/pouf.jpg";
  }
  if (product.category === "sofas" || name.includes("canapea")) {
    return "/products/studio/sofa.jpg";
  }
  if (
    name.includes("cafea") ||
    name.includes("masut") ||
    product.category === "tables" ||
    product.category === "coffee-table"
  ) {
    return "/products/studio/table.jpg";
  }
  if (product.category === "rugs" || name.includes("covor")) {
    return "/products/studio/rug.jpg";
  }
  if (
    product.category === "lighting" ||
    name.includes("lamp") ||
    name.includes("veioz")
  ) {
    return "/products/studio/lamp.jpg";
  }
  return "/products/studio/table.jpg";
}

export function uniqueProductImage(
  product: Pick<PartnerProduct, "id" | "imageUrl" | "image" | "name" | "category">,
) {
  return studioCatalogImage(product);
}

function product(input: {
  id: string;
  sku: string;
  name: string;
  description: string;
  category: ProductCategory;
  image2d: string;
  image?: string;
  accentColor: string;
  styles: InteriorStyle[];
  rooms: RoomKind[];
  promptHint: string;
  price: number;
  affiliateUrl: string;
  vendorId?: string;
  currency?: string;
  dimensions?: TypedPartnerProduct["dimensions"];
}): PartnerProduct {
  const uniqueImage = studioCatalogImage(input);
  const vendorId = input.vendorId ?? "kave-home";
  const buyUrl = officialManufacturerUrl(vendorId, input.affiliateUrl);
  return {
    ...input,
    currency: input.currency ?? "EUR",
    dimensions: input.dimensions ?? { widthCm: 80, depthCm: 80, heightCm: 80 },
    vendorId,
    style: input.styles,
    title: input.name,
    affiliateUrl: buyUrl,
    buyUrl,
    image: uniqueImage,
    imageUrl: uniqueImage,
    image2d: uniqueImage,
  };
}

